#!/usr/bin/env node
// =============================================================================
//  TM TRADING - PINE INVENTORY  (roadmap §61.17 Phase D)
//
//  Scans `pine/dist/*.pine` (the build output of tools/build.mjs) and renders
//  `docs/web-app/pine-inventory.md`. Purpose:
//
//    1. One ledger of every Pine script (kind, version, input count,
//       alertcondition count, ...) so we know exactly what the engine must
//       mirror.
//    2. A short sha256 per file, so any change to a script changes this report —
//       tests/pineInventory.test.ts then catches drift (a script edited without
//       regenerating the doc).
//
//  IMPORTANT: `.pine` files are DATA, not engine code. This script only reads
//  them as text; a guard test forbids any `import` that points at a `.pine`.
//
//  Run: npm run pine:inventory   (or --check to only verify drift, exit 1).
// =============================================================================

import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
export const ROOT = join(HERE, '..')
export const PINE_DIR = join(ROOT, 'pine', 'dist')
export const REPORT_PATH = join(ROOT, 'docs', 'web-app', 'pine-inventory.md')

function countMatches(text, regex) {
  const m = text.match(regex)
  return m ? m.length : 0
}

/** Parse one .pine file into a fixed-shape record. */
export function parsePineSource(fileName, source) {
  const lines = source.split('\n')
  const verMatch = source.match(/^\/\/@version=(\d+)/m)
  const declMatch = source.match(/^(indicator|strategy)\(\s*"([^"]*)"/m)
  return {
    file: fileName,
    title: declMatch ? declMatch[2] : fileName.replace(/\.pine$/, ''),
    kind: declMatch ? declMatch[1] : 'unknown',
    pineVersion: verMatch ? verMatch[1] : '?',
    bytes: Buffer.byteLength(source, 'utf8'),
    lines: lines.length,
    inputs: countMatches(source, /\binput\.[a-z_]+\s*\(/g),
    alerts: countMatches(source, /\balertcondition\s*\(/g),
    plotshapes: countMatches(source, /\bplotshape\s*\(/g),
    plots: countMatches(source, /^[ \t]*plot\s*\(/gm),
    sha: createHash('sha256').update(source).digest('hex').slice(0, 12),
  }
}

/** Read the whole pine/dist directory, sorted by file name (stable, no timestamp). */
export function scanPineDir(dir = PINE_DIR) {
  const files = readdirSync(dir)
    .filter((f) => f.endsWith('.pine'))
    .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0))
  return files.map((f) => parsePineSource(f, readFileSync(join(dir, f), 'utf8')))
}

function mdTable(rows) {
  const head = '| Script | Kind | Pine | Inputs | Alertcondition | plotshape | plot | Lines | Bytes | sha256[:12] |'
  const sep = '| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | --- |'
  const body = rows.map(
    (r) =>
      `| ${r.title} | ${r.kind} | v${r.pineVersion} | ${r.inputs} | ${r.alerts} | ${r.plotshapes} | ${r.plots} | ${r.lines} | ${r.bytes} | \`${r.sha}\` |`,
  )
  return [head, sep, ...body].join('\n')
}

function mdFileNameTable(rows) {
  const body = rows.map((r) => `| \`${r.file}\` | ${r.title} |`).join('\n')
  return ['| File | Title |', '| --- | --- |', body].join('\n')
}

/** Build the report markdown (pure, deterministic). */
export function renderPineInventory(rows) {
  const strategies = rows.filter((r) => r.kind === 'strategy').length
  const indicators = rows.filter((r) => r.kind === 'indicator').length
  return `# Pine inventory

Generated by \`npm run pine:inventory\` from \`pine/dist/*.pine\`. Do not edit by
hand — edit the Pine sources (or \`tools/build.mjs\`) and regenerate. The sha256
column pins each script's content, so any rebuild changes this file.

Roadmap §61.17 Phase D: the native signal engine (\`engine/signalEngine.mjs\`)
must stay honest about which scripts it mirrors. This inventory is the ledger of
those scripts; \`tests/pineInventory.test.ts\` fails if this file drifts from
\`pine/dist\`.

## Summary

- Scripts: ${rows.length} (${strategies} strategy, ${indicators} indicator)
- Pine version: ${[...new Set(rows.map((r) => r.pineVersion))].sort().join(', ')}

${mdTable(rows)}

## File map

${mdFileNameTable(rows)}

## Compatibility notes

- \`.pine\` files are data. The engine never imports or executes them; parity is
  asserted by behaviour (\`engine/test.mjs\` golden fixtures via
  \`npm run indicator:parity\`), never by running Pine.
- Repository parity between a script and a method is tracked in
  \`docs/web-app/system-integration-map.md\`, not inferred from this table.
- Compatibility (which Pine primitives the native engine implements) and the
  runtime/port decision live in \`docs/web-app/pine-compatibility.md\`
  (generated by \`npm run pine:parity\`, Phase D — D6).
`
}

export function buildPineInventory(dir = PINE_DIR) {
  const rows = scanPineDir(dir)
  return { rows, markdown: renderPineInventory(rows) }
}

function isMain() {
  return process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
}

if (isMain()) {
  const { rows, markdown } = buildPineInventory()
  const check = process.argv.includes('--check')
  if (check) {
    let current = ''
    try {
      current = readFileSync(REPORT_PATH, 'utf8')
    } catch {
      current = ''
    }
    if (current !== markdown) {
      console.error('pine:inventory --check — docs/web-app/pine-inventory.md is out of date; run npm run pine:inventory')
      process.exit(1)
    }
    console.log(`pine:inventory --check — ok (${rows.length} scripts)`)
  } else {
    writeFileSync(REPORT_PATH, markdown)
    console.log(`pine:inventory — wrote ${rows.length} scripts → docs/web-app/pine-inventory.md`)
  }
}
