#!/usr/bin/env node
// =============================================================================
//  TM TRADING - PINE COMPATIBILITY / PARITY MATRIX  (roadmap §61.17 Phase D — D6)
//
//  The Phase D gate says: "add a compatibility report and representative parity
//  tests BEFORE selecting runtime/port strategy." This module is that
//  compatibility report, derived from pine/dist/*.pine (built scripts) and the
//  native engine — never by running Pine.
//
//  For every built script it lists the Pine primitives it actually uses:
//    - ta.<fn> calls (extracted from the source text)
//    - request.security (MTF), Pine UDT, matrix, array, varip, library imports
//  and maps each ta.* primitive to the engine surface that implements it
//  (engine/ta.mjs + engine/indicators.mjs). Coverage is a per-primitive verdict
//  so a drift is a reviewable, named gap — not a vibes call.
//
//  Deterministic: sorted rows, no timestamp. Regenerate with `npm run pine:parity`.
//  tests/pineParity.test.ts pins that the committed report matches a fresh scan.
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { scanPineDir } from './pine-inventory.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..')
export const PINE_DIR = join(ROOT, 'pine', 'dist')
export const REPORT_PATH = join(ROOT, 'docs', 'web-app', 'pine-compatibility.md')

// Pine ta.* primitive -> the engine surface that implements it.
// Only primitives the built scripts ACTUALLY use are classified; a brand-new
// ta.* call surfaces as `unknown` and forces a review before any port.
//   "present"     = an exported fn of that exact name exists in the engine
//   "composable"  = no single exported fn, but trivially built from primitives
//                   the engine already implements (documented, not a gap)
//   "MISSING ..." = not implemented in the native engine yet (an honest, named
//                   gap for the runtime/port decision)
const COVERAGE = {
  sma: 'present', rma: 'present', atr: 'present', ema: 'present', rsi: 'present',
  stdev: 'present', macd: 'present', vwap: 'present', bb: 'present (indicators registry)',
  pivotlow: 'present (pivotLow)', pivothigh: 'present (pivotHigh)',
  highest: 'present', lowest: 'present',
  change: 'composable: close - close[1]',
  crossover: 'composable: cross of two series',
  crossunder: 'composable: cross of two series (inverted)',
  dmi: 'MISSING - no ta.dmi in engine',
  stoch: 'MISSING - no ta.stoch in engine',
  barssince: 'MISSING - no ta.barssince in engine',
  hma: 'MISSING - no ta.hma in engine',
  tr: 'MISSING - no ta.tr in engine (use trueRange)',
}

function strip(src) {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').split('\n').map((l) => l.replace(/\/\/.*$/, '')).join('\n')
}

/** Which Pine primitives does one built script actually use? */
export function extractFeatures(source) {
  const s = strip(source)
  const ta = [...new Set([...s.matchAll(/\bta\.([a-z][a-z0-9_]*)/g)].map((m) => m[1]))].sort()
  return {
    ta,
    mtf: /request\.security\s*\(/.test(s),
    udt: /^\s*type\s+\w+/m.test(s),
    matrix: /\bmatrix\.[a-z_]+(?:<[^<>]*>)?\s*\(/.test(s),
    arrays: /\barray\.[a-z_]+(?:<[^<>]*>)?\s*\(/.test(s),
    varip: /\bvarip\b/.test(s),
    library: /\bimport\s+/.test(s),
  }
}

/** Per-script parity row: features + coverage verdicts for its ta.* usage. */
export function parityRow(file, kind, sha, source) {
  const features = extractFeatures(source)
  const gaps = features.ta.filter((f) => COVERAGE[f] && COVERAGE[f].startsWith('MISSING'))
  const unknown = features.ta.filter((f) => !(f in COVERAGE))
  return {
    file,
    kind,
    sha,
    features,
    gaps,
    unknown,
    // A script is "covered" when it has no MISSING ta.* and no unknown ta.*.
    covered: gaps.length === 0 && unknown.length === 0,
  }
}

/** Scan pine/dist and build one parity row per script (deterministic order). */
export function buildParityMatrix() {
  return scanPineDir().map((r) => {
    const source = readFileSync(join(PINE_DIR, r.file), 'utf8')
    return parityRow(r.file, r.kind, r.sha, source)
  })
}

const flag = (b) => (b ? 'yes' : 'no')

function render(rows) {
  const total = rows.length
  const covered = rows.filter((r) => r.covered).length
  const gapSet = [...new Set(rows.flatMap((r) => r.gaps))].sort()
  const unknownSet = [...new Set(rows.flatMap((r) => r.unknown))].sort()
  const lines = []
  lines.push('# Pine compatibility report')
  lines.push('')
  lines.push('Generated by `npm run pine:parity` from `pine/dist/*.pine` and the native')
  lines.push('engine (`engine/ta.mjs` + `engine/indicators.mjs`). Do not edit by hand —')
  lines.push('change the Pine sources or the engine, then regenerate. Deterministic output.')
  lines.push('')
  lines.push('Roadmap §61.17 Phase D (D6): this is the **compatibility report** that must')
  lines.push('exist **before** selecting a runtime/port strategy for the `.pine` scripts.')
  lines.push('It is a *compatibility* verdict, not a behavioural parity proof — behaviour is')
  lines.push('pinned separately by the `engine/test.mjs` golden fixtures (`npm run indicator:parity`).')
  lines.push('')
  lines.push('## Summary')
  lines.push('')
  lines.push(`- Scripts: ${total} (covered: ${covered}, with gaps: ${total - covered})`)
  lines.push(`- MISSING ta.* primitives: ${gapSet.length ? gapSet.join(', ') : 'none'}`)
  lines.push(`- UNCLASSIFIED ta.* primitives: ${unknownSet.length ? unknownSet.join(', ') : 'none'}`)
  lines.push('')
  lines.push('## Per-script matrix')
  lines.push('')
  lines.push('| Script | Kind | ta.* used | MTF | UDT | Matrix | Arrays | varip | Library | Status |')
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |')
  for (const r of rows) {
    const feats = r.features
    const ta = feats.ta.length ? feats.ta.join(', ') : '—'
    let status = 'covered'
    if (!r.covered) {
      status = (r.gaps.length ? `gaps: ${r.gaps.join(', ')}` : '') +
        (r.gaps.length && r.unknown.length ? ' + ' : '') +
        (r.unknown.length ? `unknown: ${r.unknown.join(', ')}` : '')
    }
    lines.push(`| ${r.file} | ${r.kind} | ${ta} | ${flag(feats.mtf)} | ${flag(feats.udt)} | ${flag(feats.matrix)} | ${flag(feats.arrays)} | ${flag(feats.varip)} | ${flag(feats.library)} | ${status} |`)
  }
  lines.push('')
  lines.push('## ta.* primitive coverage (engine surface)')
  lines.push('')
  lines.push('| Pine primitive | Engine coverage |')
  lines.push('| --- | --- |')
  for (const k of Object.keys(COVERAGE).sort()) lines.push(`| \`ta.${k}\` | ${COVERAGE[k]} |`)
  lines.push('')
  lines.push('## Notes')
  lines.push('')
  lines.push('- `composable` means the primitive has no single exported engine fn but is a')
  lines.push('  trivial, documented function of primitives the engine already implements')
  lines.push('  (e.g. `ta.change` = `close - close[1]`, `ta.crossover` = a cross of two series).')
  lines.push('- `MISSING` rows are the honest, named gaps for the runtime/port decision:')
  lines.push('  porting or adding them to `engine/ta.mjs` is required before those scripts can')
  lines.push('  be mirrored natively. They are disclosed here, never silently ignored.')
  lines.push('- Behavioural parity (does the engine *compute the same values*) is proven by the')
  lines.push('  `engine/test.mjs` golden fixtures via `npm run indicator:parity`, not by this table.')
  lines.push('')
  lines.push('## Runtime / port decision')
  lines.push('')
  lines.push(...decision(gapSet, unknownSet, covered, total))
  lines.push('')
  return lines.join('\n')
}

// Deterministic, data-driven decision for the D6 gate. The recommendation is a
// pure function of the coverage verdicts above, so it can never drift from the
// matrix. The repo rule "engine core is dependency-free" rules out a Pine
// runtime, so the only viable option is porting to the native engine.
function decision(gapSet, unknownSet, covered, total) {
  const L = []
  if (gapSet.length === 0 && unknownSet.length === 0) {
    L.push(`All ${total} scripts are covered by the native engine, so every script can be`)
    L.push('mirrored as a native method. **No Pine runtime is required.**')
  } else {
    L.push(`**Decision: keep Pine as the reference / parity source; do NOT add a Pine`)
    L.push(`runtime.** The engine core is dependency-free (AGENTS.md), and a Pine runtime`)
    L.push(`would break that rule and the Pine↔engine parity discipline (risk #1).`)
    L.push(``)
    if (gapSet.length) {
      L.push(`To mirror the ${total - covered} script(s) that are not yet covered natively,`)
      L.push(`port the missing primitive(s) into \`engine/ta.mjs\` first: **${gapSet.join(', ')}**.`)
    }
    if (unknownSet.length) {
      L.push(`Classify the unclassified primitive(s) in the COVERAGE table above before any`)
      L.push(`port: **${unknownSet.join(', ')}**.`)
    }
    L.push(``)
    L.push(`Until then those scripts stay reference-only; the scripts marked \`covered\` may be`)
    L.push(`mirrored as native methods immediately.`)
  }
  return L
}

export function buildParityReport() {
  const rows = buildParityMatrix()
  return { rows, markdown: render(rows) }
}

function isMain() {
  return process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
}

if (isMain()) {
  const { rows, markdown } = buildParityReport()
  const check = process.argv.includes('--check')
  if (check) {
    let current = ''
    try { current = readFileSync(REPORT_PATH, 'utf8') } catch { current = '' }
    if (current !== markdown) {
      console.error('pine:parity --check — docs/web-app/pine-compatibility.md is out of date; run npm run pine:parity')
      process.exit(1)
    }
    console.log(`pine:parity --check — ok (${rows.length} scripts)`)
  } else {
    writeFileSync(REPORT_PATH, markdown)
    console.log(`pine:parity — wrote ${rows.length} scripts → docs/web-app/pine-compatibility.md`)
  }
}